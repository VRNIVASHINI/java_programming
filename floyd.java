import java.util.scanner;
public class floyd{
    public static void main(string[]args){
        int n=4;
        int num=1;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){
                system.out.print(num+" ");
                num++;
            }
            system.out.print();
        }
    }
}